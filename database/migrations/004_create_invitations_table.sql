CREATE TABLE IF NOT EXISTS invitations (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    template_id BIGINT NOT NULL,
    title VARCHAR(150) NOT NULL,
    slug VARCHAR(180) NOT NULL UNIQUE,
    partner_one_name VARCHAR(100) NOT NULL,
    partner_two_name VARCHAR(100) NOT NULL,
    cover_photo_path VARCHAR(255) NULL,
    event_date DATE NOT NULL,
    event_time TIME NULL,
    timezone VARCHAR(50) NOT NULL DEFAULT 'Asia/Jakarta',
    venue_name VARCHAR(150) NULL,
    venue_address TEXT NULL,
    maps_url TEXT NULL,
    description TEXT NULL,
    closing_message TEXT NULL,
    theme_color VARCHAR(30) NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'draft',
    published_at TIMESTAMP NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_invitations_user_id (user_id),
    INDEX idx_invitations_slug (slug),
    INDEX idx_invitations_status (status),
    INDEX idx_invitations_template_id (template_id),
    CONSTRAINT fk_invitations_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_invitations_template FOREIGN KEY (template_id) REFERENCES templates (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
